# Algoritmo simples

# Recebe o nome do usuário
name = input("Qual seu nome? ")

# Receba a idade do usuário
age = input("Qual sua idade? ")

# Exibe uma mensagem formatada
print()
print("Olá", name, "!")
print("Você tem", age,"anos" "!")
print()

#Usando string formatada (f)
''' o f precisa estar junto da escrita. A variavel precisa estar entre chaves para que reconheça que é uma variavel. Precisa começar e terminar com aspas'''
print(f"Olá {name}! Você tem {age} anos!")

